"""Synthetic validator guards and four real, small public-only Lean modules.

The synthetic scope helper is not the production CLI. No grid certificate,
numeric shard or purported actual250 ledger is generated by these tests.
"""
from pathlib import Path
import argparse,copy,json,os,shutil,subprocess,time
import production_full_assembly_plan as v


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path,required=True);p.add_argument('--lean',required=True)
    a=p.parse_args();root=v.plain(a.output,must_exist=False)
    v.require(not root.exists(),'Require a new test directory');root.mkdir(parents=True)
    checks=[]
    def rejected(name,fn):
        try:fn()
        except (ValueError,KeyError,FileNotFoundError) as e:
            checks.append({'name':name,'rejected':True,'reason':str(e)})
        else:raise AssertionError('Incorrectly accepted: '+name)
    rows=[{'name':'ClosureFixture.'+x,'imports':deps} for x,deps in
        [('A',[]),('B',['ClosureFixture.A']),('C',['ClosureFixture.B']),
         ('D',['ClosureFixture.C','Lean'])]]
    graph,closures=v.graph_index(rows,'ClosureFixture')
    assert closures['ClosureFixture.D']==['ClosureFixture.A','ClosureFixture.B','ClosureFixture.C']
    v.validate_order([],rows,graph)
    rejected('graph_missing_transitive',lambda:v.graph_index(rows[1:],'ClosureFixture'))
    rejected('graph_cycle',lambda:v.graph_index([{'name':'ClosureFixture.A','imports':['ClosureFixture.B']},
        {'name':'ClosureFixture.B','imports':['ClosureFixture.A']}],'ClosureFixture'))
    rejected('graph_casefold_duplicate',lambda:v.graph_index([*rows,{'name':'ClosureFixture.a','imports':[]}],'ClosureFixture'))
    rejected('graph_duplicate_import',lambda:v.graph_index([{'name':'ClosureFixture.A',
        'imports':['Lean','Lean']}],'ClosureFixture'))
    rejected('graph_bad_name',lambda:v.graph_index([{'name':'ClosureFixture../X','imports':[]}],'ClosureFixture'))
    rejected('graph_foreign',lambda:v.graph_index([{'name':'Other.A','imports':[]}],'ClosureFixture'))
    rejected('order_future_dep',lambda:v.validate_order([],list(reversed(rows)),graph))
    rejected('order_existing_collision',lambda:v.validate_order(['ClosureFixture.A'],rows,graph))
    rejected('duplicate_JSON_key',lambda:v.strict_json('{"x":1,"x":2}'))
    rejected('path_parent_escape',lambda:v.relative_path(root,'../outside'))
    rejected('path_absolute',lambda:v.relative_path(root,'/outside'))
    rejected('path_double_separator',lambda:v.relative_path(root,'a//b'))
    pinprobe=root/'pin_probe.json';v.save(pinprobe,{'scope':'synthetic'})
    pinhash=v.sha(pinprobe);v.pinned(pinprobe,pinhash)
    v.save(pinprobe,{'scope':'modified_synthetic'})
    rejected('externally_pinned_input_mutation',lambda:v.pinned(pinprobe,pinhash))
    # Canonical tuple structure only: these are expressly synthetic helper data.
    jobs=[dict(key=f'R{tag}{i:04d}',sign=sg,start=i,count=32,durable_record_sha256='1'*64)
          for tag,sg in [('P',1),('M',-1)] for i in range(0,4000,32)]
    ledger=dict(mode='full',source_revision=v.SOURCE_REVISION,plan_sha256=v.PLAN_SHA,
        base_lock_sha256=v.BASE_SHA,jobs=jobs,publication_revision='1'*40)
    merged=dict(mode='full',revision=v.SOURCE_REVISION,plan_sha256=v.PLAN_SHA,
        base_lock_sha256=v.BASE_SHA,status='inputs_prepared',all_250_projections_validated=True,
        actual_lean_import_checked=False,inter_shard_seams_proved=False,full_certificate_proved=False)
    v.full_scope(ledger,merged,v.PLAN_SHA,v.BASE_SHA)
    def scope_change(which,key,val):
        left,right=copy.deepcopy(ledger),copy.deepcopy(merged)
        (left if which=='ledger' else right)[key]=val
        v.full_scope(left,right,v.PLAN_SHA,v.BASE_SHA)
    for which,key,val in [('ledger','mode','pilot'),('merged','mode','pilot'),
        ('ledger','jobs',jobs[:-1]),('ledger','jobs',list(reversed(jobs))),
        ('ledger','jobs',[jobs[0],*jobs[:-1]]),('ledger','source_revision','2'*40),
        ('merged','base_lock_sha256','2'*64),('ledger','plan_sha256','2'*64),
        ('ledger','publication_revision',None),('merged','full_certificate_proved',True),
        ('merged','actual_lean_import_checked',True),('merged','all_250_projections_validated',False)]:
        rejected('synthetic_scope_'+which+'_'+key+'_'+str(len(checks)),lambda w=which,k=key,x=val:scope_change(w,k,x))
    badjobs=copy.deepcopy(jobs);badjobs[-1]['durable_record_sha256']=None
    rejected('synthetic_scope_no_durable',lambda:scope_change('ledger','jobs',badjobs))
    report=dict(schema='rotating.final-supplement-build.v1',status='checked',base_lock_sha256=v.BASE_SHA,
        supplement_manifest_sha256=v.FINAL_SHA,core_inventory_sha256=v.CORE_SHA,
        supplementary_modules_checked=48,conditional_geometry_audit_count=2205,
        fresh_public_only_audit_checked=True,private_project_input_files=0,extra_external_setup_modules=[],
        extra_external_setup_bindings=[],full_path_instances_checked=False,full_certificate_proved=False,
        lean={'version':'synthetic linux structural field'},
        modules=[dict(name='Synthetic.'+str(i),exit_code=0,termination='completed') for i in range(48)],
        fresh_audit=dict(name='SolitonClassification.Rotating.FinalSupplementFreshAudit',exit_code=0,termination='completed'),
        helper_sha256={n:v.HELPERS[n] for n in ['production_compile_final_supplement.py','production_compile_shard.py']})
    v.validate_final_report(report,v.BASE_SHA)
    def final_change(key,value):
        bad=copy.deepcopy(report);bad[key]=value;v.validate_final_report(bad,v.BASE_SHA)
    for key,value in [('base_lock_sha256','2'*64),('private_project_input_files',1),
        ('full_path_instances_checked',True),('modules',report['modules'][:-1]),
        ('lean',{'version':'Windows'}),('extra_external_setup_modules',['Mathlib.Fake']),
        ('fresh_audit',dict(name=report['fresh_audit']['name'],exit_code=1,termination='completed')),
        ('helper_sha256',{})]:
        rejected('synthetic_final_'+key,lambda k=key,x=value:final_change(k,x))
    # Actual small Lean verification follows. Only stdlib is an external root.
    merger,runner,_=v.load_helpers();compiler=merger.compiler
    lean,identity=compiler.lean_identity(a.lean)
    stdlib=Path(subprocess.check_output([str(lean),'--print-libdir'],text=True).strip()).resolve()
    env=os.environ.copy();env['LEAN_PATH']=str(stdlib);env['LC_ALL']='C'
    v.validate_external_roots([stdlib],'ClosureFixture')
    print('Checking actual tiny fixture stdlib before.',flush=True)
    stdlib_before=compiler.base_snapshot({'stdlib':stdlib})
    v.save(root/'stdlib_lock.json',{'lean':identity,'files':stdlib_before})
    sources=root/'source';outputs=root/'full_outputs';public=root/'public_inputs';logs=root/'logs';setups=root/'setups'
    for path in (sources,outputs,public,logs,setups):path.mkdir()
    bodies=[('A',[],'''namespace ClosureFixture
def a : Nat := 7
private theorem hidden : a = 7 := rfl
theorem a_eq : a = 7 := hidden
end ClosureFixture
'''),('B',['ClosureFixture.A'],'''namespace ClosureFixture
def b : Nat := a + 1
theorem b_eq : b = 8 := rfl
end ClosureFixture
'''),('C',['ClosureFixture.B'],'''namespace ClosureFixture
def c : Nat := b + 1
theorem c_eq : c = 9 := rfl
end ClosureFixture
'''),('D',['ClosureFixture.C','Lean'],'''namespace ClosureFixture
theorem result : c = 9 := c_eq
end ClosureFixture
#print axioms ClosureFixture.result
open Lean Elab Command in
run_cmd do
  unless (← collectAxioms `ClosureFixture.result).isEmpty do throwError "Unexpected fixture axiom"
  logInfo "FOUR_MODULE_RECURSIVE_PUBLIC_CLOSURE_CHECKED"
''')]
    available={};results=[];source_records={};fixture_hash=v.sha(__file__);validator_hash=v.sha(v.__file__)
    for short,imports,body in bodies:
        name='ClosureFixture.'+short;source=sources/('ClosureFixture/'+short+'.lean');source.parent.mkdir(exist_ok=True)
        source.write_text('module\n'+''.join('public import '+n+'\n' for n in imports)+
            '\n@[expose] public section\n'+body,encoding='utf-8',newline='\n')
        source_records[name]=v.record(source)
        assert compiler.header_imports(source)==imports
        runner.parse_header(lean,source,env,runner.expected_header(imports),logs/(short+'.imports.json'))
        v.validate_public_tree(public,available)
        setup=v.closure_setup(name,closures,available,public);v.validate_setup(setup,setup)
        if imports:
            v.validate_final_setup(setup,name,{n:available[n] for n in closures[name]})
        setup_path=setups/(short+'.json');v.save(setup_path,setup)
        target=outputs/v.module_path(name);target.parent.mkdir(exist_ok=True)
        command=[str(lean),'--setup',str(setup_path),'-j','1','-M','2048','-o',str(target),str(source)]
        started=time.monotonic();child=subprocess.run(command,cwd=sources,env=env,capture_output=True,text=True,timeout=60)
        text=child.stdout+child.stderr;(logs/(short+'.log')).write_text(text,encoding='utf-8')
        if child.returncode or 'error:' in text or 'warning:' in text:raise RuntimeError(text)
        if short=='D':assert 'FOUR_MODULE_RECURSIVE_PUBLIC_CLOSURE_CHECKED' in text
        artifacts=compiler.bundle(target);assert set(artifacts)==set(compiler.SIDE)
        pub=public/v.module_path(name);pub.parent.mkdir(exist_ok=True);shutil.copyfile(target,pub)
        available[name]=artifacts['']
        results.append(dict(name=name,exit_code=child.returncode,source=source_records[name],
            setup=v.record(setup_path),log=v.record(logs/(short+'.log')),artifacts=artifacts,
            mapped_project_names=list(setup['importArts']),wall_seconds=time.monotonic()-started))
        print('ACTUAL',name,'EXIT 0',flush=True)
    v.validate_public_tree(public,available)
    expected=v.closure_setup('ClosureFixture.D',closures,available,public)
    bad=copy.deepcopy(expected);del bad['importArts']['ClosureFixture.A']
    rejected('setup_missing_transitive',lambda:v.validate_setup(bad,expected))
    private=copy.deepcopy(expected);private['importArts']['ClosureFixture.A'][0].append(str(outputs/'ClosureFixture/A.olean.private'))
    rejected('setup_private_layer',lambda:v.validate_setup(private,expected))
    override=copy.deepcopy(expected);override['imports']=[]
    rejected('setup_source_import_override',lambda:v.validate_setup(override,expected))
    selected={n:available[n] for n in closures['ClosureFixture.D']}
    rejected('archived_setup_private_layer',lambda:v.validate_final_setup(private,'ClosureFixture.D',selected))
    rejected('archived_setup_source_import_override',lambda:v.validate_final_setup(override,'ClosureFixture.D',selected))
    wrong_origin=copy.deepcopy(expected)
    wrong_origin['importArts']['ClosureFixture.A'][0][0]=wrong_origin['importArts']['ClosureFixture.A'][0][0].replace('public_inputs','other_inputs')
    rejected('archived_setup_wrong_origin',lambda:v.validate_final_setup(wrong_origin,'ClosureFixture.D',selected))
    rejected('archived_setup_missing_transitive',lambda:v.validate_final_setup(bad,'ClosureFixture.D',selected))
    rejected('fallback_contains_project',lambda:v.validate_external_roots([stdlib,outputs],'ClosureFixture'))
    rejected('closure_missing_available',lambda:v.closure_setup('ClosureFixture.D',closures,
        {k:r for k,r in available.items() if k!='ClosureFixture.A'},public))
    # Deliberately bypass setup validator for ONE actual negative Lean experiment.
    # A primary still exists in public_inputs, and its private output remains in
    # full_outputs; neither directory is on LEAN_PATH, so neither may rescue A.
    missing=setups/'D_missing_transitive.json';v.save(missing,bad)
    negative=subprocess.run([str(lean),'--setup',str(missing),str(sources/'ClosureFixture/D.lean')],
        cwd=sources,env=env,capture_output=True,text=True,timeout=60)
    negtext=negative.stdout+negative.stderr;(logs/'missing_transitive.log').write_text(negtext,encoding='utf-8')
    v.require(negative.returncode!=0 and 'ClosureFixture' in negtext,'Missing transitive import unexpectedly succeeded')
    # File-inventory rejection probes use new copies, preserving actual originals.
    probe=root/'public_probe';shutil.copytree(public,probe)
    (probe/'ClosureFixture/A.olean.private').write_bytes(b'not a real artifact')
    rejected('public_tree_private',lambda:v.validate_public_tree(probe,available))
    (probe/'ClosureFixture/A.olean.private').unlink();(probe/'ClosureFixture/A.olean').write_bytes(b'changed')
    rejected('public_tree_changed',lambda:v.validate_public_tree(probe,available))
    for name,rec in source_records.items():assert v.record(sources/(v.module_path(name)[:-6]+'.lean'))==rec
    for result in results:assert compiler.bundle(outputs/v.module_path(result['name']))==result['artifacts']
    v.validate_public_tree(public,available)
    assert compiler.lean_identity(str(lean))[1]==identity
    print('Checking actual tiny fixture stdlib after.',flush=True)
    assert compiler.base_snapshot({'stdlib':stdlib})==stdlib_before
    assert v.sha(__file__)==fixture_hash and v.sha(v.__file__)==validator_hash
    v.load_helpers()
    summary=dict(schema='rotating.assembly-plan-tests.v1',status='passed',
        structural_fixture_scope='synthetic internal helper data only; production full CLI was not called',
        rejection_checks=checks,actual_tiny_lean_modules=results,actual_project_private_inputs=0,
        actual_missing_transitive=dict(exit_code=negative.returncode,log=v.record(logs/'missing_transitive.log'),
            absent_mapping='ClosureFixture.A',primary_and_private_exist_outside_search=True),
        mapped_project_counts=[len(x['mapped_project_names']) for x in results],
        actual_full250_validation=False,actual_full_assembly_Lean_calls=0,full_certificate_proved=False,
        validator_sha256=validator_hash,fixture_sha256=fixture_hash,lean=identity,
        stdlib_lock_sha256=v.sha(root/'stdlib_lock.json'),whole_stdlib_before_after_unchanged=True)
    v.save(root/'report.json',summary)
    print(json.dumps({'status':'passed','actual_tiny_modules':4,'negative_Lean_exit':negative.returncode,
        'structural_rejections':len(checks),'report_sha256':v.sha(root/'report.json')}),flush=True)


if __name__=='__main__':main()

