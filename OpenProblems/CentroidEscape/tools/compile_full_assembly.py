"""Compile the complete five-path assembly only from verified shard artifacts.

Run via lake env with the audited core in LEAN_PATH. All shard reports, source,
logs, artifacts and direct dependency hashes are checked before compilation.
The final audit is always compiled afresh. Generation and preflight never prove
the certificate. A success flag is written only after actual Lean execution.
"""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor, wait, FIRST_COMPLETED
import argparse
import hashlib
import json
import os
import re
import shutil
import signal
import subprocess
import sys
import tempfile
import threading
import time
import traceback
from types import SimpleNamespace
if hasattr(sys.stdout,"reconfigure"):
    sys.stdout.reconfigure(errors="backslashreplace")

import assemble_full_certificate as assembly
from compile_shard import atomic_report, digest, windows_memory

COMPILER_SHA256 = digest(Path(__file__))
SUPPORT_HASHES = {name: digest(Path(__file__).with_name(name)) for name in
                  ("assemble_full_certificate.py", "compile_shard.py")}
REPORT_PATH = None
LIVE_REPORT = None
AUDIT_MESSAGE = "Strict full certificate audit passed: unconditional smooth FEF centroid escape."


def contained_file(directory, relative):
    path = (directory / relative).resolve()
    if not path.is_relative_to(directory.resolve()) or not path.is_file():
        raise ValueError(f"Missing file or escaping evidence path: {path}")
    return path


def direct_imports(source):
    text = source.read_text(encoding="utf-8")
    imports = re.findall(r"^import\s+([A-Za-z0-9_.]+)\s*$", text, re.MULTILINE)
    if len(imports) != len(re.findall(r"^import\b", text, re.MULTILINE)):
        raise ValueError(f"Unexpected import syntax in {source}")
    if re.search(r"\b(sorry|admit|native_decide|axiom)\b", text):
        # Generated sources have no such tokens, even in comments.
        raise ValueError(f"Forbidden proof placeholder/native axiom in {source}")
    return imports


def validate_assembly(manifest_path, manifest_list, candidate_override):
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("schema") != "centroid.full-certificate-assembly.v1":
        raise ValueError("Not a full-certificate assembly manifest")
    if manifest.get("generator_sha256") != SUPPORT_HASHES["assemble_full_certificate.py"]:
        raise ValueError("Assembly was generated by a different assembler version; regenerate")
    if manifest_list:
        paths = assembly.collect_paths(SimpleNamespace(manifest=[],manifest_list=manifest_list,shards_root=None))
    else:
        paths = [Path(item["path"]).resolve() for item in manifest["input_shards"]]
    expected = {item["sha256"] for item in manifest["input_shards"]}
    if len(paths) != len(expected) or {digest(p) for p in paths} != expected:
        raise ValueError("Input shard manifest set differs from full assembly")
    candidate_path = candidate_override or Path(manifest["candidate_source"]["path"])
    candidate = assembly.read_candidate(candidate_path.resolve())
    if candidate["sha256"] != manifest["candidate_source"]["sha256"]:
        raise ValueError("Candidate source hash mismatch")
    groups = assembly.validate_manifests(paths,candidate)
    # Regeneration pins the exact intended theorem and audit, not only hashes
    # supplied by an arbitrary edited manifest. Paths may relocate between OSs.
    with tempfile.TemporaryDirectory(prefix="centroid-assembly-check-") as temp:
        regenerated = json.loads(assembly.generate(groups,candidate,Path(temp),False).read_text())
        for field in ("key","expected_steps","steps_per_case","case_order","modules",
                      "root_module","audit_module","checked_theorem","escape_theorem",
                      "required_generic_modules"):
            if manifest.get(field) != regenerated[field]:
                raise ValueError(f"Assembly regeneration mismatch: {field}")
    for item in manifest["modules"]:
        source = contained_file(manifest_path.parent,item["source"])
        if digest(source) != item["sha256"]:
            raise ValueError(f"Assembly source mismatch: {item['name']}")
        direct_imports(source)
    return manifest,groups


def report_paths(report_index):
    if report_index is None:
        return {}
    raw = json.loads(report_index.read_text(encoding="utf-8"))
    if raw.get("schema") != "centroid.shard-report-index.v1":
        raise ValueError("Expected centroid.shard-report-index.v1")
    result = {}
    for item in raw["reports"]:
        key = item["manifest_sha256"]
        if key in result:
            raise ValueError("Duplicate shard report index entry")
        path = Path(item["report"])
        result[key] = path.resolve() if path.is_absolute() else (report_index.parent/path).resolve()
        if "sha256" in item and digest(result[key]) != item["sha256"]:
            raise ValueError("Report index hash mismatch")
    return result


def validate_shard_reports(groups,report_index,lean_version):
    overrides = report_paths(report_index)
    artifacts, evidence, expected_imports = {}, [], {}
    required_hashes = {item["manifest_sha256"] for group in groups.values() for item in group}
    if overrides and set(overrides) != required_hashes:
        raise ValueError("Report index must cover precisely all input shards")
    for case in assembly.CASES:
        for record in groups[case]:
            manifest = record["data"]
            report_path = overrides.get(record["manifest_sha256"],Path(record["manifest"]).parent/"compile_report.json")
            report = json.loads(report_path.read_text(encoding="utf-8"))
            if (report.get("schema") != "centroid.compact-shard-build.v1" or
                report.get("status") != "checked" or report.get("shard_kernel_checked") is not True or
                report.get("manifest_sha256") != record["manifest_sha256"] or
                report.get("key") != manifest["key"] or report.get("lean_version") != lean_version):
                raise ValueError(f"Unverified/stale/incompatible shard report: {report_path}")
            if report.get("compiler_sha256") != SUPPORT_HASHES["compile_shard.py"]:
                raise ValueError(f"Unknown shard compiler provenance: {report_path}")
            entries = report.get("modules",[])
            if [e.get("name") for e in entries] != [m["name"] for m in manifest["modules"]]:
                raise ValueError("Shard report module coverage/order differs from manifest")
            for source_item,entry in zip(manifest["modules"],entries):
                name=source_item["name"]
                if entry.get("exit_code") != 0 or entry.get("source_sha256") != source_item["sha256"]:
                    raise ValueError(f"Failed or mismatched shard module: {name}")
                source=contained_file(Path(record["manifest"]).parent,source_item["source"])
                imports=direct_imports(source)
                hashes=entry.get("import_hashes",{})
                if set(imports) != set(hashes):
                    raise ValueError(f"Incomplete dependency provenance: {name}")
                for imported,expected in hashes.items():
                    if not re.fullmatch(r"[0-9a-f]{64}",expected):
                        raise ValueError("Invalid dependency hash")
                    if imported in expected_imports and expected_imports[imported] != expected:
                        raise ValueError(f"Shards used incompatible versions of {imported}")
                    expected_imports[imported]=expected
                log=contained_file(report_path.parent,entry["log"])
                artifact=contained_file(report_path.parent,entry["checked_olean"])
                if digest(log) != entry["log_sha256"] or digest(artifact) != entry["olean_sha256"]:
                    raise ValueError(f"Shard evidence hash mismatch: {name}")
                if artifact.stat().st_size <= 0 or artifact.stat().st_size != entry["olean_bytes"]:
                    raise ValueError(f"Shard artifact size mismatch: {name}")
                if name in artifacts:
                    raise ValueError(f"Duplicate shard artifact: {name}")
                artifacts[name]={"path":artifact,"sha256":entry["olean_sha256"]}
                if name == manifest["audit_module"]:
                    if entry.get("audit_message_seen") is not True or "Strict shard audit passed" not in log.read_text(encoding="utf-8"):
                        raise ValueError("Shard audit evidence is missing")
            evidence.append({"path":str(report_path),"sha256":digest(report_path),
                             "manifest_sha256":record["manifest_sha256"],"key":manifest["key"]})
    for name,artifact in artifacts.items():
        if name in expected_imports and expected_imports[name] != artifact["sha256"]:
            raise ValueError(f"Shard internal dependency does not match its producer: {name}")
    return artifacts,evidence,expected_imports


def main():
    global REPORT_PATH,LIVE_REPORT
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest",type=Path,required=True)
    parser.add_argument("--manifest-list",type=Path,help="Relocated shard manifest index, if needed")
    parser.add_argument("--candidate-source",type=Path,help="Relocated exact CandidateEndpointChecks.lean")
    parser.add_argument("--report-index",type=Path,help="Optional centroid.shard-report-index.v1 for relocated evidence")
    parser.add_argument("--lean",default="lean")
    parser.add_argument("--build-root",type=Path,required=True)
    parser.add_argument("--jobs",type=int,default=1)
    parser.add_argument("--memory-mb",type=int,default=8192)
    parser.add_argument("--resume-verified",action="store_true")
    args=parser.parse_args()
    manifest_path=args.manifest.resolve()
    directory=manifest_path.parent
    directory.mkdir(parents=True,exist_ok=True)
    REPORT_PATH=directory/"full_compile_report.json"
    old={}
    if args.resume_verified and REPORT_PATH.is_file():
        try: old=json.loads(REPORT_PATH.read_text(encoding="utf-8"))
        except (ValueError,OSError): pass
    LIVE_REPORT={"schema":"centroid.full-certificate-build.v1","status":"running",
                 "full_certificate_proved":False,"compiler_sha256":COMPILER_SHA256,
                 "support_sha256":SUPPORT_HASHES,"modules":[]}
    atomic_report(REPORT_PATH,LIVE_REPORT)
    if args.jobs<1 or args.memory_mb<1:
        raise ValueError("Positive jobs and memory cap required")
    manifest,groups=validate_assembly(manifest_path,args.manifest_list,args.candidate_source)
    build=args.build_root.resolve()
    build.mkdir(parents=True,exist_ok=True)
    environment=os.environ.copy()
    roots=[Path(p).resolve() for p in environment.get("LEAN_PATH","").split(os.pathsep) if p]
    if build not in roots: roots.append(build)
    environment["LEAN_PATH"]=os.pathsep.join(map(str,roots))
    environment["LC_ALL"]="C"
    lean=shutil.which(args.lean) or str(Path(args.lean).resolve())
    if not Path(lean).is_file(): raise FileNotFoundError("Lean executable missing")
    version=subprocess.check_output([lean,"--version"],env=environment,text=True).strip()
    artifacts,evidence,expected_imports=validate_shard_reports(groups,args.report_index,version)

    def output_path(name): return build/Path(*name.split(".")).with_suffix(".olean")
    def first_hit(name):
        relative=Path(*name.split(".")).with_suffix(".olean")
        found=next((root/relative for root in roots if (root/relative).is_file()),None)
        if found is None: raise FileNotFoundError(f"Missing dependency: {name}")
        return found

    # Stage only evidence-verified artifacts. Copies are atomic; source artifacts
    # stay immutable and all first-hit hashes must agree with original reports.
    for name,artifact in artifacts.items():
        destination=output_path(name)
        destination.parent.mkdir(parents=True,exist_ok=True)
        if not destination.is_file() or digest(destination)!=artifact["sha256"]:
            descriptor,temp_name=tempfile.mkstemp(prefix=".input-",suffix=".olean",dir=destination.parent)
            os.close(descriptor)
            temporary=Path(temp_name)
            try:
                shutil.copyfile(artifact["path"],temporary)
                if digest(temporary)!=artifact["sha256"]: raise ValueError("Shard artifact changed while staging")
                temporary.replace(destination)
            finally:
                if temporary.exists(): temporary.unlink()
    for name,expected in {**expected_imports,**{n:a["sha256"] for n,a in artifacts.items()}}.items():
        if digest(first_hit(name))!=expected:
            raise ValueError(f"Shadowed/incompatible shard or core dependency: {name}")

    modules=manifest["modules"]
    names={item["name"] for item in modules}
    by_name={item["name"]:item for item in modules}
    sources={item["name"]:contained_file(directory,item["source"]) for item in modules}
    imports={name:direct_imports(source) for name,source in sources.items()}
    dependencies={name:set(items)&names for name,items in imports.items()}
    logs=directory/"logs"; logs.mkdir(exist_ok=True)
    checked=directory/"checked_oleans"; checked.mkdir(exist_ok=True)
    manifest_hash=digest(manifest_path)
    previous={}
    if (args.resume_verified and old.get("key")==manifest["key"] and old.get("lean_version")==version and
        old.get("manifest_sha256")==manifest_hash and old.get("compiler_sha256")==COMPILER_SHA256 and
        old.get("support_sha256")==SUPPORT_HASHES):
        previous={e["name"]:e for e in old.get("modules",[]) if e.get("exit_code")==0}
    LIVE_REPORT.update(key=manifest["key"],manifest_sha256=manifest_hash,lean_version=version,
        jobs=args.jobs,memory_mb_per_process=args.memory_mb,lean_threads_per_process=1,
        shard_reports=evidence,shard_module_count=len(artifacts),checked_theorem=manifest["checked_theorem"],
        escape_theorem=manifest["escape_theorem"],axioms_allowed=["propext","Classical.choice","Quot.sound"])
    results={};abort=threading.Event();print_lock=threading.Lock();started=time.monotonic()

    def save():
        LIVE_REPORT["modules"]=[results[m["name"]] for m in modules if m["name"] in results]
        LIVE_REPORT["wall_ms"]=round((time.monotonic()-started)*1000)
        atomic_report(REPORT_PATH,LIVE_REPORT)

    def dependency_hashes(name):
        hashes={}
        for imported in imports[name]:
            path=first_hit(imported)
            hashed=digest(path)
            if imported in names:
                producer=results.get(imported)
                if path.resolve()!=output_path(imported).resolve() or not producer or producer.get("exit_code")!=0 or producer.get("olean_sha256")!=hashed:
                    raise ValueError(f"Assembly dependency shadowed or not produced by this run: {imported}")
            elif imported in artifacts and hashed!=artifacts[imported]["sha256"]:
                raise ValueError(f"Shard dependency changed: {imported}")
            elif imported in expected_imports and hashed!=expected_imports[imported]:
                raise ValueError(f"Core dependency changed: {imported}")
            hashes[imported]=hashed
        return hashes

    def run_module(name):
        item=by_name[name];source=sources[name]
        if digest(source)!=item["sha256"]: raise ValueError(f"Source changed: {name}")
        deps=dependency_hashes(name)
        output=output_path(name); output.parent.mkdir(parents=True,exist_ok=True)
        prior=previous.get(name)
        valid_prior=False
        if prior and name!=manifest["audit_module"]:
            try:
                log=contained_file(directory,prior["log"])
                valid_prior=(prior.get("source_sha256")==item["sha256"] and prior.get("import_hashes")==deps and
                             digest(log)==prior["log_sha256"] and output.is_file() and digest(output)==prior.get("olean_sha256"))
            except (KeyError,OSError,ValueError): pass
        if valid_prior:
            result=dict(prior);result["reused_verified"]=True
        else:
            log_path=logs/(name.split(".")[-1]+".log")
            resource_path=logs/(name.split(".")[-1]+".resource.txt")
            descriptor,temp_name=tempfile.mkstemp(prefix=".full-",suffix=".olean",dir=output.parent)
            os.close(descriptor);temporary=Path(temp_name);temporary.unlink()
            command=[lean,"-M",str(args.memory_mb),"-j","1","-o",str(temporary),str(source)]
            timed=sys.platform.startswith("linux") and Path("/usr/bin/time").is_file()
            if timed: command=["/usr/bin/time","-v","-o",str(resource_path)]+command
            begin=time.monotonic();peak_resident=0;sampled_private=0;audit_seen=False;read_errors=[]
            try:
                with log_path.open("w",encoding="utf-8") as log:
                    process=subprocess.Popen(command,env=environment,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,
                        text=True,encoding="utf-8",errors="replace",creationflags=subprocess.CREATE_NO_WINDOW if os.name=="nt" else 0,
                        start_new_session=(os.name=="posix"))
                    def read_output():
                        nonlocal audit_seen
                        try:
                            for line in process.stdout:
                                log.write(line);log.flush()
                                if AUDIT_MESSAGE in line: audit_seen=True
                                with print_lock: print(f"[{name.split('_')[-1]}] {line.rstrip()}",flush=True)
                        except BaseException as error:
                            read_errors.append(repr(error));abort.set()
                    reader=threading.Thread(target=read_output,daemon=True);reader.start()
                    terminated=None
                    while process.poll() is None:
                        resident,private=windows_memory(process)
                        peak_resident=max(peak_resident,resident or 0);sampled_private=max(sampled_private,private or 0)
                        if abort.is_set():
                            try:
                                if terminated is None:
                                    if os.name=="posix": os.killpg(process.pid,signal.SIGTERM)
                                    else: process.terminate()
                                    terminated=time.monotonic()
                                elif time.monotonic()-terminated>5:
                                    if os.name=="posix": os.killpg(process.pid,signal.SIGKILL)
                                    else: process.kill()
                            except ProcessLookupError: pass
                        time.sleep(.1)
                    reader.join();code=process.wait()
                if read_errors: code=98
                if timed and resource_path.exists():
                    match=re.search(r"Maximum resident set size \(kbytes\):\s*(\d+)",resource_path.read_text())
                    if match: peak_resident=1024*int(match.group(1))
                if code==0 and (not temporary.is_file() or temporary.stat().st_size==0 or
                               (name==manifest["audit_module"] and not audit_seen)):
                    code=97
                if code==0 and (digest(source)!=item["sha256"] or dependency_hashes(name)!=deps):
                    code=96
                if code==0: temporary.replace(output)
            finally:
                if temporary.exists(): temporary.unlink()
            result={"name":name,"source_sha256":item["sha256"],"import_hashes":deps,"exit_code":code,
                    "wall_ms":round((time.monotonic()-begin)*1000),"peak_resident_bytes":peak_resident or None,
                    "sampled_peak_private_bytes":sampled_private or None,"log":log_path.relative_to(directory).as_posix(),
                    "log_sha256":digest(log_path),"audit_message_seen":audit_seen,"reused_verified":False}
            if code==0: result.update(olean_sha256=digest(output),olean_bytes=output.stat().st_size)
        if result["exit_code"]==0:
            destination=checked/Path(*name.split(".")).with_suffix(".olean")
            destination.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(output,destination)
            result["checked_olean"]=destination.relative_to(directory).as_posix()
        with print_lock: print(f"MODULE {name} EXIT={result['exit_code']} WALL_MS={result['wall_ms']} RSS={result.get('peak_resident_bytes')}",flush=True)
        return result

    save();pending=[m["name"] for m in modules];done=set();active={};failure=None
    with ThreadPoolExecutor(max_workers=args.jobs) as executor:
        try:
            while pending or active:
                if not abort.is_set():
                    ready=[name for name in pending if dependencies[name]<=done]
                    for name in ready[:max(0,args.jobs-len(active))]:
                        pending.remove(name);active[executor.submit(run_module,name)]=name
                if not active:
                    if pending and failure is None: failure="Unresolved/cyclic assembly dependencies"
                    break
                finished,_=wait(active,return_when=FIRST_COMPLETED)
                for future in finished:
                    name=active.pop(future)
                    try: result=future.result()
                    except Exception as error: result={"name":name,"exit_code":98,"error":repr(error)}
                    results[name]=result
                    if result["exit_code"]==0: done.add(name)
                    else: failure=f"Module failed: {name}";abort.set()
                    save()
        except BaseException:
            abort.set()  # Also stop child process groups on an interrupted build.
            raise
    success=(failure is None and done==names and results[manifest["audit_module"]].get("audit_message_seen") is True)
    if success:
        # Final snapshot rejects evidence changes during a long assembly build.
        if digest(manifest_path)!=manifest_hash: raise ValueError("Assembly manifest changed during compilation")
        for item in evidence:
            if digest(Path(item["path"]))!=item["sha256"]: raise ValueError("Shard report changed during compilation")
        for group in groups.values():
            for record in group:
                path=Path(record["manifest"])
                if digest(path)!=record["manifest_sha256"]: raise ValueError("Shard manifest changed during compilation")
                for item in record["data"]["modules"]:
                    if digest(contained_file(path.parent,item["source"]))!=item["sha256"]:
                        raise ValueError("Shard source changed during compilation")
        for name,expected in expected_imports.items():
            if digest(first_hit(name))!=expected: raise ValueError("Shard dependency changed during compilation")
        for name,artifact in artifacts.items():
            if digest(first_hit(name))!=artifact["sha256"]: raise ValueError("Shard artifact changed during compilation")
        for name in names:
            if digest(sources[name])!=by_name[name]["sha256"] or dependency_hashes(name)!=results[name]["import_hashes"]:
                raise ValueError("Assembly input changed during compilation")
            if digest(output_path(name))!=results[name]["olean_sha256"]: raise ValueError("Assembly artifact changed during compilation")
    LIVE_REPORT.update(status="checked" if success else "failed",full_certificate_proved=success)
    if failure: LIVE_REPORT["failure"]=failure
    save()
    print(f"FULL_CERTIFICATE_PROVED={str(success).lower()} REPORT={REPORT_PATH}",flush=True)
    return 0 if success else 1


if __name__=="__main__":
    try:
        raise SystemExit(main())
    except BaseException as error:
        if isinstance(error,SystemExit): raise
        if REPORT_PATH is not None:
            failed=LIVE_REPORT or {}
            failed.update(status="failed",full_certificate_proved=False,failure=repr(error),compiler_sha256=COMPILER_SHA256)
            atomic_report(REPORT_PATH,failed)
        traceback.print_exc()
        raise SystemExit(1)
